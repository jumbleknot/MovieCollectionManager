// Item #552 — gen-dev-secrets.mjs must COMPLETE an existing <stack>.env, never silently leave it
// incomplete.
//
// Why this guard exists. In the dev container `stacks/mcm.env` held six Mongo/agent keys and none of
// the four BACKUP_TEST_* credentials the feature-073 backup destinations need. gen-dev-env.mjs then
// had nothing to project, `describeBackupTargets` skipped nine integration suites, and a skip reads as
// a pass. The generator had to deliver the missing keys to the EXISTING file without rotating a
// single value the running stacks were started with — `--force` would take them all down to add one.
//
// The generator resolves its stacks directory from its own path, so these tests copy it into a
// throwaway mini-repo with a synthetic template. They are offline and keyless and never touch the
// developer's real stacks/*.env. Values are synthetic fixtures; the assertions check that no value —
// fixture or minted — is ever printed.
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const REAL_SCRIPT = resolve(REPO_ROOT, 'scripts/gen-dev-secrets.mjs');

const TEMPLATE = [
  '# synthetic mcm template',
  'AGENT_DB_PASSWORD=<generate:b62-32>',
  'MONGO_MC_APP_PASSWORD=<generate:complex-16>',
  'BACKUP_TEST_S3_ACCESS_KEY=mcmbackuptest',
  'BACKUP_TEST_S3_SECRET_KEY=<generate:complex-16>',
  'BACKUP_TEST_WEBDAV_USER=mcmbackuptest',
  'BACKUP_TEST_WEBDAV_PASSWORD=<generate:complex-16>',
  'REGISTRY_HOST=',
  '',
].join('\n');

const BACKUP_KEYS = [
  'BACKUP_TEST_S3_ACCESS_KEY',
  'BACKUP_TEST_S3_SECRET_KEY',
  'BACKUP_TEST_WEBDAV_USER',
  'BACKUP_TEST_WEBDAV_PASSWORD',
];

function miniRepo(existingMcmEnv) {
  const root = mkdtempSync(resolve(tmpdir(), 'gen-dev-secrets-'));
  const stacks = resolve(root, 'infrastructure-as-code/docker/stacks');
  mkdirSync(resolve(root, 'scripts'), { recursive: true });
  mkdirSync(stacks, { recursive: true });
  copyFileSync(REAL_SCRIPT, resolve(root, 'scripts/gen-dev-secrets.mjs'));
  writeFileSync(resolve(stacks, 'mcm.env.example'), TEMPLATE, 'utf8');
  if (existingMcmEnv !== undefined) writeFileSync(resolve(stacks, 'mcm.env'), existingMcmEnv, 'utf8');
  return { root, mcmEnv: resolve(stacks, 'mcm.env') };
}

function run(root) {
  const r = spawnSync(process.execPath, [resolve(root, 'scripts/gen-dev-secrets.mjs'), '--stack=mcm'], {
    encoding: 'utf8',
  });
  return { status: r.status, out: `${r.stdout}${r.stderr}` };
}

function parse(path) {
  const map = new Map();
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line);
    if (m) map.set(m[1], m[2]);
  }
  return map;
}

/** Every non-trivial value in the file must be absent from the generator's output. */
function assertNoValueEchoed(out, path) {
  for (const [key, value] of parse(path)) {
    if (value.length < 8) continue; // blank / short fixtures cannot be meaningfully searched for
    assert.ok(!out.includes(value), `the value of ${key} was printed`);
  }
}

const PRIOR = [
  '# GENERATED by scripts/gen-dev-secrets.mjs — DO NOT COMMIT (gitignored).',
  'AGENT_DB_PASSWORD=priorAgentValueFixture0123456789',
  'MONGO_MC_APP_PASSWORD=priorMongoFixture-1',
  '',
].join('\n');

test('#552: an EXISTING mcm.env missing the BACKUP_TEST_* keys has all four seeded', () => {
  const { root, mcmEnv } = miniRepo(PRIOR);
  const { status, out } = run(root);
  assert.equal(status, 0, out);
  const env = parse(mcmEnv);
  for (const k of BACKUP_KEYS) assert.ok(env.get(k), `${k} was not seeded`);
  assert.equal(env.get('BACKUP_TEST_S3_ACCESS_KEY'), 'mcmbackuptest', 'fixture copied verbatim');
  assert.equal(env.get('BACKUP_TEST_S3_SECRET_KEY').length, 16, 'placeholder minted with its kind');
});

test('#552: back-filling NEVER rotates a value the file already holds', () => {
  const { root, mcmEnv } = miniRepo(PRIOR);
  run(root);
  const env = parse(mcmEnv);
  assert.equal(env.get('AGENT_DB_PASSWORD'), 'priorAgentValueFixture0123456789');
  assert.equal(env.get('MONGO_MC_APP_PASSWORD'), 'priorMongoFixture-1');
  assert.ok(readFileSync(mcmEnv, 'utf8').startsWith(PRIOR), 'existing lines kept byte-for-byte');
});

test('#552: the seeded keys are NAMED in the output, and no value is printed', () => {
  const { root, mcmEnv } = miniRepo(PRIOR);
  const { out } = run(root);
  for (const k of BACKUP_KEYS) assert.match(out, new RegExp(k), `${k} not named in output`);
  assertNoValueEchoed(out, mcmEnv);
});

test('#552: a generated key present but EMPTY is minted — an empty secret is a missing secret', () => {
  // `KEY=` defines the key and holds nothing. Counting it as present reproduces the original defect:
  // the run says "up to date", compose's ${KEY:?} refuses (or the suite skips), and nothing names why.
  const { root, mcmEnv } = miniRepo(`${PRIOR}BACKUP_TEST_WEBDAV_PASSWORD=\n`);
  const { status, out } = run(root);
  assert.equal(status, 0, out);
  const env = parse(mcmEnv);
  assert.equal(env.get('BACKUP_TEST_WEBDAV_PASSWORD')?.length, 16, 'empty placeholder key was not minted');
  assert.match(out, /BACKUP_TEST_WEBDAV_PASSWORD/);
  assert.equal(env.get('AGENT_DB_PASSWORD'), 'priorAgentValueFixture0123456789');
  const occurrences = readFileSync(mcmEnv, 'utf8').match(/^BACKUP_TEST_WEBDAV_PASSWORD=/gm) ?? [];
  assert.equal(occurrences.length, 1, 'the key must be filled in place, not duplicated');
  assertNoValueEchoed(out, mcmEnv);
});

test('#552: a fixture key the TEMPLATE leaves blank is not treated as missing (REGISTRY_HOST)', () => {
  // REGISTRY_HOST is deliberately blank in the template (set per machine). A blank value there is not
  // a gap the generator can fill, so a complete file must still report up to date.
  const complete = [
    PRIOR.trimEnd(),
    'BACKUP_TEST_S3_ACCESS_KEY=mcmbackuptest',
    'BACKUP_TEST_S3_SECRET_KEY=priorS3Fixture-123',
    'BACKUP_TEST_WEBDAV_USER=mcmbackuptest',
    'BACKUP_TEST_WEBDAV_PASSWORD=priorDavFixture-12',
    'REGISTRY_HOST=',
    '',
  ].join('\n');
  const { root, mcmEnv } = miniRepo(complete);
  const { status, out } = run(root);
  assert.equal(status, 0, out);
  assert.match(out, /up to date/);
  assert.equal(readFileSync(mcmEnv, 'utf8'), complete, 'a complete file is not rewritten');
});
