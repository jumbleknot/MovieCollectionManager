#!/usr/bin/env node
// Regenerates scripts/__tests__/fixtures/cc-usage/ccusage-oracle.json (feature 105, research R8).
//
// Run ONLY through `pnpm nx cc-usage-oracle infrastructure-as-code`. It fetches ccusage at the exact
// version below with `pnpm dlx`, points it at the synthetic fixtures (never the real transcripts),
// and keeps per-session token totals only, so the output is deterministic and reviewable. CI never
// runs this: it compares the parser with the committed file instead (cc-usage-oracle.test.mjs).
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CCUSAGE_VERSION = '20.0.48';
const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const FIXTURES = join(REPO, 'scripts', '__tests__', 'fixtures', 'cc-usage');

const r = spawnSync('pnpm', ['dlx', `ccusage@${CCUSAGE_VERSION}`, 'session', '--json', '--offline'], {
  cwd: REPO,
  encoding: 'utf8',
  env: { ...process.env, CLAUDE_CONFIG_DIR: FIXTURES },
});
if (r.status !== 0) {
  process.stderr.write(r.stderr || r.stdout);
  process.exit(1);
}
const json = JSON.parse(r.stdout.slice(r.stdout.indexOf('{'), r.stdout.lastIndexOf('}') + 1));
const sessions = {};
for (const s of json.session ?? []) {
  const id = s.period ?? s.sessionId;
  sessions[id] = {
    input: s.inputTokens,
    output: s.outputTokens,
    cache_write: s.cacheCreationTokens,
    cache_read: s.cacheReadTokens,
  };
}
if (Object.keys(sessions).length === 0) {
  // An empty oracle would make the cross-check pass vacuously.
  process.stderr.write('ccusage reported no sessions — refusing to write an empty oracle\n');
  process.exit(1);
}
const sorted = Object.fromEntries(Object.entries(sessions).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  join(FIXTURES, 'ccusage-oracle.json'),
  JSON.stringify({
    $comment: 'Generated by `pnpm nx cc-usage-oracle infrastructure-as-code` — do not edit by hand. Per-session totals (main transcript + its subagent files) from the reference tool over the synthetic fixtures (research R8).',
    tool: `ccusage@${CCUSAGE_VERSION}`,
    sessions: sorted,
  }, null, 2) + '\n',
);
console.log(`ccusage-oracle.json: ${Object.keys(sorted).length} sessions`);
